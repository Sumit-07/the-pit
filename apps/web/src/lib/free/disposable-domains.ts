/**
 * The disposable-domain list, checked in.
 *
 * ## Why a list at all, and why it is a file rather than a vendor call
 *
 * The free first throw is the one place in The Pit where a stranger spends our
 * money: a run is twelve juror calls, a clustering pass and a persona round, and
 * `brief §2.3` prices that at $5 for everybody else. The whole of the free
 * throw's defence is that a person gets exactly one, and "one" only means
 * anything if the identity it is counted against costs something to obtain. A
 * mailinator address costs nothing and can be minted a thousand times a minute,
 * so an unfiltered email is not an identity — it is a counter the attacker holds.
 *
 * A third-party disposable-domain API would be a better list and a much worse
 * dependency: it puts a network call, a key, a vendor outage and somebody else's
 * uptime on the path of the request that decides whether we spend money. This
 * file cannot time out, cannot rate-limit us, and is reviewable in a diff. It
 * will go stale, and staleness here fails in the safe direction — a domain we
 * have not heard of falls through to the four rules AFTER this one (`url_used`,
 * `email_used`, `ip_window`, `daily_cap`), none of which it can evade.
 *
 * ## Matching is exact-or-subdomain, and that is deliberate
 *
 * `mailinator.com` also refuses `team.mailinator.com`, because every one of these
 * services hands out unlimited subdomains as a feature. It does NOT refuse
 * `ourmailinator.com`: the match walks the domain's LABELS rather than scanning
 * the string, so the boundary is a dot and never a character offset. A plain
 * `endsWith` would refuse a real company whose name happened to end in a listed
 * string, which is a paying customer turned away by a spam list.
 *
 * (`notmailinator.com` IS on the list, and is the reason that example is not the
 * one used here: it is a genuine Mailinator alias, not a false positive.)
 *
 * ## What this list is not
 *
 * It is not a judgement about the person, and it is not a spam score. A refusal
 * here costs somebody a FREE run and nothing else — the $5 door is untouched,
 * and `brief §2.3` keeps "same five dollars for everyone" literally true because
 * that door never asks who you are.
 *
 * Sorted, lowercase and unique, asserted by `test/free-policy.test.ts`: a domain
 * added in the wrong place fails the suite rather than sitting in a list nobody
 * can scan.
 */

