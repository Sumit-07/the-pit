/**
 * The same list as a set, built once at module load.
 *
 * The exact match is the overwhelmingly common case — almost every disposable
 * address is at the bare domain — so it is one hash lookup, and only a miss pays
 * for the walk up the labels.
 */
const EXACT = new Set(DISPOSABLE_EMAIL_DOMAINS);

/**
 * Is this domain disposable, either exactly or as a subdomain of one that is?
 *
 * The walk is up the LABELS: `a.b.mailinator.com` asks about
 * `a.b.mailinator.com`, then `b.mailinator.com`, then `mailinator.com`, and
 * never about `ailinator.com`. A domain has a handful of labels, so this is a
 * handful of set lookups and no allocation worth counting.
 */
export function isDisposableDomain(domain: string): boolean {
  const normalized = domain.trim().toLowerCase().replace(/\.$/, '');
  if (normalized === '') return false;

  const labels = normalized.split('.');
  for (let i = 0; i < labels.length; i += 1) {
    if (EXACT.has(labels.slice(i).join('.'))) return true;
  }
  return false;
}
